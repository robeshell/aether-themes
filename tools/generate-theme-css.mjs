#!/usr/bin/env node

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const themeNames = ['minimal', 'magazine', 'terminal', 'cyber', 'island', 'wilds', 'persona'];
const args = process.argv.slice(2);

if (args.includes('--help') || args.includes('-h')) {
  console.log('用法：aether-themes [--config aether.config.mjs] [--output src/styles/aether-themes.css] [--source package|local]');
  process.exit(0);
}

function valueFor(flag, fallback) {
  const index = args.indexOf(flag);
  return index === -1 ? fallback : args[index + 1];
}

const configPath = resolve(valueFor('--config', 'aether.config.mjs'));
const outputPath = resolve(valueFor('--output', 'src/styles/aether-themes.css'));
const source = valueFor('--source', 'package');

if (!['package', 'local'].includes(source)) {
  console.error('`--source` 只能是 package 或 local。');
  process.exit(1);
}

let config;
try {
  config = (await import(pathToFileURL(configPath).href)).default;
} catch (error) {
  console.error(`无法读取配置文件：${configPath}`);
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}

const enabledThemes = config?.themes ?? themeNames;
if (!Array.isArray(enabledThemes) || enabledThemes.length === 0) {
  console.error('aether.config.mjs 的 themes 必须是至少包含一个主题的数组。');
  process.exit(1);
}

const unknownThemes = enabledThemes.filter((theme) => !themeNames.includes(theme));
if (unknownThemes.length > 0) {
  console.error(`未知主题：${unknownThemes.join(', ')}`);
  console.error(`可用主题：${themeNames.join(', ')}`);
  process.exit(1);
}

const duplicates = enabledThemes.filter((theme, index) => enabledThemes.indexOf(theme) !== index);
if (duplicates.length > 0) {
  console.error(`主题不能重复：${[...new Set(duplicates)].join(', ')}`);
  process.exit(1);
}

const defaultTheme = config.defaultTheme ?? enabledThemes[0];
if (!enabledThemes.includes(defaultTheme)) {
  console.error(`defaultTheme (${defaultTheme}) 必须属于 themes。`);
  process.exit(1);
}

const imports = source === 'local'
  ? ['./global.css', ...enabledThemes.map((theme) => `./themes/${theme}.css`)]
  : ['aether-themes/foundation.css', ...enabledThemes.map((theme) => `aether-themes/themes/${theme}.css`)];

const contents = [
  '/* Generated by Aether. Edit aether.config.mjs, then run the generator again. */',
  `/* Enabled themes: ${enabledThemes.join(', ')}; default: ${defaultTheme} */`,
  ...imports.map((path) => `@import '${path}';`),
  '',
].join('\n');

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, contents, 'utf8');
console.log(`已生成 ${outputPath}`);
console.log(`启用主题：${enabledThemes.join(', ')}`);
console.log(`默认主题：${defaultTheme}`);
